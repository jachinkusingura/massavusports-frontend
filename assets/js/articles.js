    function saveArticle(articleObj) {
        const all = getAllArticles();
        const idx = all.findIndex(a => String(a.id) === String(articleObj.id));
        if (idx >= 0) {
            all[idx] = { ...all[idx], ...articleObj };
        } else {
            all.unshift(articleObj);
        }
        localStorage.setItem(STORAGE_KEY_POSTS, JSON.stringify(all));
        return all;
    }

